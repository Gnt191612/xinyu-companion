rows = []
for state, prompt, opening, story in examples:
    emotion = 'sadness' if state.startswith(('委屈', '难过')) else ('anxiety' if state == '焦虑' else ('joy' if state.startswith('开心') else 'neutral'))
    reply = opening + '\n\n' + story
    rows.append({'history': [{'role': 'user', 'content': prompt}], 'response_text': reply,
                 'emotion_label': emotion, 'category': '状态适配完整故事', '状态与偏好': state})
    rows.append({'history': [{'role': 'user', 'content': prompt}, {'role': 'assistant', 'content': '好呀，我来讲。'},
                            {'role': 'user', 'content': '好的呢'}], 'response_text': story,
                 'emotion_label': emotion, 'category': '助手讲述短确认后实际执行'})
for old_index, new_index in [(0,1), (1,2), (3,4), (6,7), (9,10), (10,11)]:
    first, second = examples[old_index], examples[new_index]
    rows.append({'history': [{'role':'user','content':first[1]}, {'role':'assistant','content':first[2]+'\n\n'+first[3]},
                            {'role':'user','content':'再讲一个吧，换个角色和场景，不要重复刚才的故事。'}],
                 'response_text':'好呀，这次换个故事。\n\n'+second[3], 'emotion_label': 'sadness' if first[0].startswith(('委屈','难过')) else ('anxiety' if first[0]=='焦虑' else 'neutral'), 'category':'同状态连续换故事'})
