for split, samples in [('train', rows), ('dev', dev)]:
    for i, sample in enumerate(samples,1):sample['id']=f'story_{split}_{i:06d}'
    (OUT/f'{split}.jsonl').write_text(''.join(json.dumps(x,ensure_ascii=False)+'\n' for x in samples),encoding='utf8')
